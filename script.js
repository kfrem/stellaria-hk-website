const setLanguage = (lang) => {
  document.documentElement.lang = lang === "zh" ? "zh-Hans" : "en";
  document.body.classList.toggle("lang-zh", lang === "zh");
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (translations[lang][key]) {
      node.textContent = translations[lang][key];
    }
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("active", button.getAttribute("data-lang") === lang);
  });
  localStorage.setItem("stellaria-language", lang);
};

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.getAttribute("data-lang")));
});

const header = document.querySelector(".site-header");
const updateHeader = () => {
  header.dataset.scrolled = window.scrollY > 36 ? "true" : "false";
};

window.addEventListener("scroll", updateHeader, { passive: true });
updateHeader();
setLanguage(localStorage.getItem("stellaria-language") || "en");
