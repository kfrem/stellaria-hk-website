const setLanguage = (lang) => {
  document.documentElement.lang = lang === "zh" ? "zh-Hans" : "en";
  document.body.classList.toggle("lang-zh", lang === "zh");
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (translations[lang][key]) node.textContent = translations[lang][key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    const key = node.getAttribute("data-i18n-html");
    if (translations[lang][key]) node.innerHTML = translations[lang][key];
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("active", button.getAttribute("data-lang") === lang);
  });
  localStorage.setItem("stellaria-language", lang);
};

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.getAttribute("data-lang")));
});

document.getElementById("contactForm").addEventListener("submit", (event) => {
  event.preventDefault();
  const data = new FormData(event.currentTarget);
  const subject = encodeURIComponent(`Stellaria partnership enquiry - ${data.get("company")}`);
  const body = encodeURIComponent(
    [
      `Name: ${data.get("name")}`,
      `Company: ${data.get("company")}`,
      `Email: ${data.get("email")}`,
      `Interest: ${data.get("interest")}`,
      "",
      data.get("message"),
    ].join("\n")
  );
  window.location.href = `mailto:official@stellaria-hk.com?subject=${subject}&body=${body}`;
});

